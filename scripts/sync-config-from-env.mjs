/**
 * Writes js/config.js from .env.local (browser app does not read .env files).
 * Usage: npm run config:sync
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, '.env.local');
const outPath = join(root, 'js', 'config.js');

if (!existsSync(envPath)) {
    console.error('Missing .env.local — copy .env.local.example and set SUPABASE_ANON_KEY.');
    process.exit(1);
}

const env = Object.fromEntries(
    readFileSync(envPath, 'utf8')
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith('#'))
        .map((line) => {
            const i = line.indexOf('=');
            return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
        })
);

const url = env.SUPABASE_URL || 'https://ygizkwgkbutczbctislm.supabase.co';
const key = (env.SUPABASE_ANON_KEY || '').replace(/\s+/g, '');

if (!key || key.includes('YOUR_SUPABASE')) {
    console.error('Set SUPABASE_ANON_KEY in .env.local (Dashboard → Settings → API → anon public).');
    process.exit(1);
}

const contents = `/** Generated by npm run config:sync — do not commit */\n\nexport const SUPABASE_URL = '${url}';\n\nexport const SUPABASE_ANON_KEY = '${key}';\n`;

writeFileSync(outPath, contents, 'utf8');
console.log('Wrote js/config.js from .env.local');
